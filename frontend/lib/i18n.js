export function getUiCopy(language) {
  const selected = UI_COPY[language] || UI_COPY.en;

  return Object.fromEntries(
    Object.entries(UI_COPY.en).map(([key, fallbackValue]) => [
      key,
      isUsableTranslation(selected[key]) ? selected[key] : fallbackValue
    ])
  );
}

function isUsableTranslation(value) {
  return typeof value === "string" && value.trim().length > 0;
}
